#!/usr/bin/env bash
# Sweep RVS gst (GPU stress) across {1,2,4,8} GPUs x all supported precisions,
# and report achieved TFLOPS per GPU plus aggregate.
#
# Uses the locally-built RVS in ./install_local. No root required.
#
# Tunables (env vars):
#   RVS_BIN          path to rvs binary       (default: auto-detected, see below)
#   DURATION_MS      per-test stress duration (default: 30000)
#   LOG_INTERVAL_MS  per-test log interval    (default: 3000)
#   GPU_COUNTS       space-separated counts   (default: "1 2 4 8")
#   PRECISIONS       space-separated names    (default: all 9 precisions)
#   OUT_DIR          output directory         (default: <script_dir>/tflops_runs/<timestamp>)
#
# Output:
#   $OUT_DIR/<gpus>x_<precision>.log   raw rvs stdout for each run
#   $OUT_DIR/<gpus>x_<precision>.conf  generated conf file used
#   $OUT_DIR/summary.csv               gpus,precision,per_gpu_peak_tflops,...,aggregate_tflops
#   $OUT_DIR/summary.txt               pretty table

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Auto-detect the rvs binary. Search order:
#   1. $RVS_BIN if explicitly set
#   2. <script_dir>/install_local/bin/rvs           (script + RVS colocated)
#   3. <script_dir>/../ROCmValidationSuite/install_local/bin/rvs   (sibling clone)
#   4. /opt/rocm/bin/rvs                            (system install)
#   5. `rvs` on PATH
if [[ -z "${RVS_BIN:-}" ]]; then
  for candidate in \
      "$ROOT_DIR/install_local/bin/rvs" \
      "$ROOT_DIR/../ROCmValidationSuite/install_local/bin/rvs" \
      "/opt/rocm/bin/rvs" \
      "$(command -v rvs 2>/dev/null || true)"; do
    if [[ -n "$candidate" && -x "$candidate" ]]; then
      RVS_BIN="$candidate"
      break
    fi
  done
fi

DURATION_MS="${DURATION_MS:-60000}"
LOG_INTERVAL_MS="${LOG_INTERVAL_MS:-3000}"
RAMP_INTERVAL_MS="${RAMP_INTERVAL_MS:-5000}"
GPU_COUNTS="${GPU_COUNTS:-1 2 4 8}"
PRECISIONS_DEFAULT="fp4 fp6 bf6 fp8 bf8 fp16 bf16 fp32 fp64"
PRECISIONS="${PRECISIONS:-$PRECISIONS_DEFAULT}"

TS="$(date +%Y%m%d_%H%M%S)"
OUT_DIR="${OUT_DIR:-$ROOT_DIR/tflops_runs/$TS}"
mkdir -p "$OUT_DIR"

if [[ -z "${RVS_BIN:-}" || ! -x "$RVS_BIN" ]]; then
  echo "ERROR: rvs binary not found." >&2
  echo "Tried:" >&2
  echo "  \$RVS_BIN" >&2
  echo "  $ROOT_DIR/install_local/bin/rvs" >&2
  echo "  $ROOT_DIR/../ROCmValidationSuite/install_local/bin/rvs" >&2
  echo "  /opt/rocm/bin/rvs" >&2
  echo "  rvs on PATH" >&2
  echo "Set RVS_BIN=/path/to/rvs to override." >&2
  exit 1
fi
echo "Using rvs binary: $RVS_BIN"

# Discover GPU IDs. Format from `rvs -g` is:
#   "<BDF> - GPU[ <node_id> - <gpu_id>] <model>"
# We want <gpu_id>, which is the second number inside the brackets.
mapfile -t GPU_IDS < <("$RVS_BIN" -g 2>/dev/null \
  | awk 'match($0, /GPU\[[[:space:]]*[0-9]+[[:space:]]*-[[:space:]]*[0-9]+\]/) {
           s=substr($0, RSTART, RLENGTH);
           n=split(s, a, "-");
           gsub(/[^0-9]/, "", a[2]);
           print a[2]
         }')

if (( ${#GPU_IDS[@]} == 0 )); then
  echo "ERROR: no AMD GPUs detected by '$RVS_BIN -g'" >&2
  exit 1
fi

echo "Detected ${#GPU_IDS[@]} GPU(s): ${GPU_IDS[*]}"
echo "Output dir: $OUT_DIR"
echo

# Emit a conf YAML for one (n_gpus, precision) test. Parameters match
# install_local/share/rocm-validation-suite/conf/MI355X/levels/rvs_level_5.conf
# with target_stress=0 (measure only) and a shorter duration.
emit_conf() {
  local outfile="$1" prec="$2" devices="$3"

  # Common header
  cat >"$outfile" <<EOF
# Auto-generated by run_tflops.sh
# precision=$prec  devices="$devices"  duration_ms=$DURATION_MS
actions:
- name: tflops-${prec}
  device: $devices
  module: gst
  log_interval: $LOG_INTERVAL_MS
  ramp_interval: $RAMP_INTERVAL_MS
  duration: $DURATION_MS
  copy_matrix: false
  target_stress: 0
  parallel: true
  blas_source: hipblaslt
  transa: 1
  transb: 0
EOF

  case "$prec" in
    fp4)
      cat >>"$outfile" <<'EOF'
  hot_calls: 10000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 16384
  scale_a: block
  scale_b: block
  matrix_init: trig
  data_type: fp4_r
  out_data_type: bf16_r
  compute_type: fp32_r
  alpha: 1.0
  beta: 0.0
  rotating: 512
EOF
      ;;
    fp6)
      cat >>"$outfile" <<'EOF'
  hot_calls: 10000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 16384
  scale_a: block
  scale_b: block
  matrix_init: trig
  data_type: fp6_e3m2_r
  out_data_type: bf16_r
  compute_type: fp32_r
  alpha: 1.0
  beta: 0.0
  rotating: 512
EOF
      ;;
    bf6)
      cat >>"$outfile" <<'EOF'
  hot_calls: 10000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 16384
  scale_a: block
  scale_b: block
  matrix_init: trig
  data_type: fp6_e2m3_r
  out_data_type: bf16_r
  compute_type: fp32_r
  alpha: 1.0
  beta: 0.0
  rotating: 512
EOF
      ;;
    fp8)
      cat >>"$outfile" <<'EOF'
  hot_calls: 10000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 16384
  matrix_init: trig
  data_type: fp8_e4m3_r
  out_data_type: bf16_r
  compute_type: fp32_r
  alpha: 1.0
  beta: 0.0
  rotating: 512
EOF
      ;;
    bf8)
      cat >>"$outfile" <<'EOF'
  hot_calls: 10000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 16384
  matrix_init: trig
  data_type: fp8_e5m2_r
  out_data_type: bf16_r
  compute_type: fp32_r
  alpha: 1.0
  beta: 0.0
  rotating: 512
EOF
      ;;
    fp16)
      cat >>"$outfile" <<'EOF'
  hot_calls: 10000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 16384
  matrix_init: trig
  data_type: fp16_r
  out_data_type: fp16_r
  compute_type: fp32_r
  alpha: 1
  beta: 0
  rotating: 512
EOF
      ;;
    bf16)
      cat >>"$outfile" <<'EOF'
  hot_calls: 10000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 16384
  matrix_init: trig
  data_type: bf16_r
  out_data_type: bf16_r
  compute_type: fp32_r
  alpha: 1
  beta: 0
  rotating: 512
EOF
      ;;
    fp32)
      cat >>"$outfile" <<'EOF'
  hot_calls: 2000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 8192
  matrix_init: trig
  data_type: fp32_r
  compute_type: fp32_r
  lda: 8192
  ldb: 8192
  ldc: 8192
  alpha: 1
  beta: 0
EOF
      ;;
    fp64)
      cat >>"$outfile" <<'EOF'
  hot_calls: 2000
  matrix_size_a: 8192
  matrix_size_b: 8192
  matrix_size_c: 8192
  matrix_init: trig
  data_type: fp64_r
  compute_type: fp64_r
  lda: 8192
  ldb: 8192
  ldc: 8192
  alpha: 1
  beta: 0
EOF
      ;;
    *)
      echo "ERROR: unknown precision '$prec'" >&2
      return 1
      ;;
  esac
}

# Parse a log: take the max GFLOPS value per gpu_id (steady-state proxy),
# sum to an aggregate, then print "per_gpu_peaks_csv,aggregate_tflops".
# Aggregation is on GFLOPS, converted to TFLOPS once at the end.
parse_log() {
  local logfile="$1"
  awk '
    /GFLOPS[[:space:]]+[0-9]+/ {
      # Extract GPU id from "[GPU::  NNNN]" and the GFLOPS number
      gid=""; gfl=0
      if (match($0, /GPU::[[:space:]]*[0-9]+/)) {
        s=substr($0, RSTART, RLENGTH); gsub(/[^0-9]/, "", s); gid=s
      }
      if (match($0, /GFLOPS[[:space:]]+[0-9]+/)) {
        s=substr($0, RSTART, RLENGTH); gsub(/[^0-9]/, "", s); gfl=s+0
      }
      if (gid != "" && gfl > peak[gid]) peak[gid]=gfl
    }
    END {
      out=""; sum=0; n=0
      # Sort gpu ids for deterministic order
      k=0; for (g in peak) ids[k++]=g
      # Simple insertion sort
      for (i=1; i<k; i++) {
        v=ids[i]; j=i-1
        while (j>=0 && (ids[j]+0) > (v+0)) { ids[j+1]=ids[j]; j-- }
        ids[j+1]=v
      }
      for (i=0; i<k; i++) {
        g=ids[i]
        tflops = peak[g]/1000.0
        out = (out=="" ? "" : out ";") sprintf("gpu%s=%.2f", g, tflops)
        sum += tflops
        n++
      }
      printf "%s,%.2f,%d\n", out, sum, n
    }
  ' "$logfile"
}

SUMMARY_CSV="$OUT_DIR/summary.csv"
SUMMARY_TXT="$OUT_DIR/summary.txt"
echo "gpus,precision,per_gpu_peak_tflops,aggregate_tflops,gpus_reporting" >"$SUMMARY_CSV"
{
  printf "%-5s %-6s %-12s %-14s  %s\n" "GPUs" "Prec" "Aggregate" "Avg/GPU" "Per-GPU peaks (TFLOPS)"
  printf -- "--------------------------------------------------------------------------------\n"
} >"$SUMMARY_TXT"

for n in $GPU_COUNTS; do
  if (( n > ${#GPU_IDS[@]} )); then
    echo "Skipping GPU count $n (only ${#GPU_IDS[@]} available)"
    continue
  fi
  # First n GPU ids, space separated
  devs="${GPU_IDS[*]:0:$n}"

  for prec in $PRECISIONS; do
    tag="${n}x_${prec}"
    conf="$OUT_DIR/$tag.conf"
    log="$OUT_DIR/$tag.log"

    echo "=== ${n} GPU(s) | ${prec} | devices=[$devs] ==="
    emit_conf "$conf" "$prec" "$devs"

    if ! "$RVS_BIN" -c "$conf" >"$log" 2>&1; then
      echo "  WARN: rvs exited non-zero. See $log"
    fi

    line="$(parse_log "$log")"      # "gpuN=T;gpuM=T,sum,reporting"
    peaks="${line%,*,*}"
    rest="${line#*,}"
    agg="${rest%,*}"
    reporting="${line##*,}"
    avg="0"
    if [[ "$reporting" -gt 0 ]]; then
      avg=$(awk -v a="$agg" -v r="$reporting" 'BEGIN{ printf("%.2f", a/r) }')
    fi

    echo "${n},${prec},\"${peaks}\",${agg},${reporting}" >>"$SUMMARY_CSV"
    printf "%-5s %-6s %-12s %-14s  %s\n" "${n}" "${prec}" "${agg}" "${avg}" "${peaks}" \
      >>"$SUMMARY_TXT"
    echo "  -> aggregate=${agg} TFLOPS  avg/GPU=${avg} TFLOPS  reporting=${reporting}/${n}"
  done
done

echo
echo "=== Done ==="
echo "Summary:"
cat "$SUMMARY_TXT"
echo
echo "CSV:    $SUMMARY_CSV"
echo "Logs:   $OUT_DIR/*.log"
echo "Confs:  $OUT_DIR/*.conf"
